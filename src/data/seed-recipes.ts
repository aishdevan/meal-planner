type PantryKey = keyof typeof CATALOG;

/** Build an ingredient from the catalog so keys/stores/categories stay consistent. */
function ing(key: PantryKey, qty_text: string, for_addon = false): Ingredient {
  const c: CatalogEntry = CATALOG[key];
  return {
    name: c.name,
    qty_text,
    pantry_key: key,
    store: c.store,
    category: c.category,
    staple: c.staple,
    for_addon,
  };
}

